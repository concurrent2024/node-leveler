#!/usr/bin/env python3
"""Generate docs/configuration.md from chart/values.yaml.

The values file is the single source of truth: section markers (`# --- x ---`)
become headings, the trailing comment on each config key becomes its description.
Run after editing chart/values.yaml:  python3 scripts/gen-config-docs.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VALUES = ROOT / "chart" / "values.yaml"
OUT = ROOT / "docs" / "configuration.md"

def main() -> int:
    lines = VALUES.read_text().splitlines()
    try:
        start = next(i for i, l in enumerate(lines) if l.rstrip() == "config:")
    except StopIteration:
        print("no `config:` block in values.yaml", file=sys.stderr)
        return 1

    sections, cur = [], None
    for raw in lines[start + 1:]:
        if not raw.strip() or raw.lstrip().startswith("#") and "---" not in raw:
            continue
        m_sec = re.match(r"^\s{2}#\s*-+\s*(.+?)\s*-+\s*$", raw)
        if m_sec:
            cur = (m_sec.group(1).strip(), [])
            sections.append(cur)
            continue
        m_kv = re.match(r"^\s{2}([A-Z0-9_]+):\s*(.*?)\s*(?:#\s*(.*))?$", raw)
        if m_kv:
            key, value, desc = m_kv.group(1), m_kv.group(2).strip(), (m_kv.group(3) or "").strip()
            if cur is None:
                cur = ("General", [])
                sections.append(cur)
            cur[1].append((key, value, desc))

    total = sum(len(items) for _, items in sections)
    out = [
        "# Configuration reference",
        "",
        "<!-- generated by scripts/gen-config-docs.py — edit chart/values.yaml instead -->",
        "",
        "Every key below is a field of `config:` in the chart values. It is rendered into one",
        "ConfigMap and read as environment variables by the balancer.",
        "",
        "Defaults are the chart defaults, which are intentionally conservative:",
        "`MODE=dry-run` and `suspend: true`. Start there, watch the plan for a few days,",
        "then flip `MODE` to `live`.",
        "",
        "The effective values of a running round are dumped in its first log line",
        '(`{"kind":"config"}`) — use that when a key seems to have no effect. A misspelled',
        "key silently falls back to its built-in default.",
        "",
        f"_{total} keys._",
        "",
    ]
    for title, items in sections:
        out += [f"## {title}", "", "| Key | Default | Meaning |", "|---|---|---|"]
        for key, value, desc in items:
            # pipes would break the table: escape them
            cell = (desc or "—").replace("|", "\\|")
            out.append(f"| `{key}` | `{value}` | {cell} |")
        out.append("")

    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({total} keys)")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
